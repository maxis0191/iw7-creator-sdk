"""Printed paper: crisp typography from real fonts, ink layers, paper synthesis and ageing (deterministic).

Doc draws at SS x supersampling into one mask per ink colour; render() composites the inks onto a synthesized paper
with a multiply blend (ink absorbs light, paper shows through knocked-out type), slight bleed and uneven inking. Ageing
helpers (yellowing, folds, water stains, foxing, fading, tape, staples, torn edges, photocopy) work on float arrays.
Text is never generated by a model: everything legible here is set from a font, so it is spelled exactly as written.
"""
import os

import numpy as np
from PIL import Image, ImageDraw, ImageFont
from scipy import ndimage

from . import noise as N

FONT_DIR = os.environ.get('IWZ_FONT_DIR', r'C:\Windows\Fonts')
SS = 3


def font(name, size, variation=None):
    """name: 'din' (Bahnschrift, the Zero Line sign face), 'typewriter' (Courier New), 'serif' (Times New Roman),
    'serif_bold', 'impact', 'mono' (Lucida Console). variation: a Bahnschrift instance such as 'Bold Condensed'."""
    files = {'din': 'bahnschrift.ttf', 'typewriter': 'cour.ttf', 'typewriter_bold': 'courbd.ttf',
             'serif': 'times.ttf', 'serif_bold': 'timesbd.ttf', 'serif_italic': 'timesi.ttf',
             'georgia_bold': 'georgiab.ttf', 'impact': 'impact.ttf', 'mono': 'lucon.ttf', 'arial_bold': 'arialbd.ttf'}
    f = ImageFont.truetype(os.path.join(FONT_DIR, files[name]), int(size))
    if variation:
        f.set_variation_by_name(variation)
    f.iwz_variation = variation
    return f


def fit_font(name, text, max_w, start, variation=None, min_size=6):
    s = start
    while s > min_size:
        f = font(name, s, variation)
        if f.getlength(text) <= max_w:
            return f
        s -= 1
    return font(name, min_size, variation)


def wrap(text, f, max_w):
    lines = []
    for para in text.split('\n'):
        cur = ''
        for word in para.split(' '):
            trial = (cur + ' ' + word).strip()
            if f.getlength(trial) <= max_w or not cur:
                cur = trial
            else:
                lines.append(cur)
                cur = word
        lines.append(cur)
    return lines


class Doc:
    """Ink layers on a w x h page (coordinates in final pixels; drawn at SS x)."""

    def __init__(self, w, h, ss=SS):
        self.w, self.h, self.ss = w, h, ss
        self.layers = {}            # colour tuple -> L image (ss scale)
        self.order = []

    def _layer(self, colour):
        colour = tuple(colour)
        if colour not in self.layers:
            self.layers[colour] = Image.new('L', (self.w * self.ss, self.h * self.ss), 0)
            self.order.append(colour)
        return ImageDraw.Draw(self.layers[colour])

    def _f(self, f):
        """The same font at ss x size (keeps the Bahnschrift instance)."""
        g = ImageFont.truetype(f.path, int(round(f.size * self.ss)))
        if getattr(f, 'iwz_variation', None):
            g.set_variation_by_name(f.iwz_variation)
        return g

    def text(self, xy, s, f, colour, anchor='la', spacing=0, knock=None, tracking=0):
        """Draw s; knock=colour removes the text from that ink layer (reverse type on a printed bar)."""
        S = self.ss
        g = self._f(f)
        x, y = xy[0] * S, xy[1] * S
        targets = [(self._layer(colour), 255)]
        if knock is not None:
            for kc in (knock if isinstance(knock, list) else [knock]):
                targets.append((self._layer(kc), 0))
        if tracking:
            # manual letter spacing: place glyph by glyph
            total = sum(g.getlength(c) for c in s) + tracking * S * (len(s) - 1)
            if anchor[0] == 'm':
                x -= total / 2
            elif anchor[0] == 'r':
                x -= total
            for c in s:
                for d, v in targets:
                    d.text((x, y), c, font=g, fill=v, anchor='l' + anchor[1])
                x += g.getlength(c) + tracking * S
            return
        for d, v in targets:
            d.text((x, y), s, font=g, fill=v, anchor=anchor, spacing=spacing * S)

    def para(self, x, y, s, f, colour, max_w, leading=1.25, anchor='la', align='left'):
        lines = wrap(s, f, max_w)
        lh = f.size * leading
        for i, ln in enumerate(lines):
            xx = x
            if align == 'center':
                xx, a = x + max_w / 2, 'm' + anchor[1]
            else:
                a = anchor
            self.text((xx, y + i * lh), ln, f, colour, anchor=a)
        return y + len(lines) * lh

    def rect(self, box, colour, width=0, knock=None, radius=0):
        S = self.ss
        b = [box[0] * S, box[1] * S, box[2] * S, box[3] * S]
        d = self._layer(colour)
        if width:
            d.rounded_rectangle(b, radius=radius * S, outline=255, width=int(width * S)) if radius else \
                d.rectangle(b, outline=255, width=int(width * S))
        else:
            d.rounded_rectangle(b, radius=radius * S, fill=255) if radius else d.rectangle(b, fill=255)
        if knock is not None:
            self._layer(knock).rectangle(b, fill=0)

    def line(self, pts, colour, width=1):
        S = self.ss
        self._layer(colour).line([(x * S, y * S) for x, y in pts], fill=255, width=max(1, int(width * S)))

    def ellipse(self, box, colour, width=0, knock=None):
        S = self.ss
        b = [v * S for v in box]
        d = self._layer(colour)
        if width:
            d.ellipse(b, outline=255, width=int(width * S))
        else:
            d.ellipse(b, fill=255)
            if knock is not None:
                ImageDraw.Draw(self.layers[tuple(knock)]).ellipse(b, fill=0)

    def polygon(self, pts, colour):
        S = self.ss
        self._layer(colour).polygon([(x * S, y * S) for x, y in pts], fill=255)

    def image(self, im, box):
        """Place a halftoned/greyscale photo as black ink (darkness = ink)."""
        S = self.ss
        x0, y0, x1, y1 = [int(v * S) for v in box]
        g = im.convert('L').resize((x1 - x0, y1 - y0), Image.LANCZOS)
        ink = Image.eval(g, lambda v: 255 - v)
        self._layer((0.08, 0.08, 0.08))
        self.layers[(0.08, 0.08, 0.08)].paste(ink, (x0, y0))

    def masks(self):
        out = []
        for c in self.order:
            m = self.layers[c].resize((self.w, self.h), Image.LANCZOS)
            out.append((np.array(c, np.float32), np.asarray(m, np.float32) / 255))
        return out

    def render(self, paper_rgb, seed=0, bleed=0.45, uneven=0.12, fade=0.0, misreg=0.0):
        out = np.array(paper_rgb, np.float32, copy=True)
        for i, (c, m) in enumerate(self.masks()):
            if misreg and i > 0:
                m = ndimage.shift(m, (misreg * (i % 2 * 2 - 1), misreg * 0.5), order=1)
            if bleed:
                m = ndimage.gaussian_filter(m, bleed)
            if uneven:
                m = m * (1 - uneven + uneven * N.fbm(m.shape, seed + i * 17, 4, base=0.02))
            m = m * (1 - fade)
            out = out * (1 - m[..., None] * (1 - c[None, None, :]))
        return out


def paper(w, h, seed=0, colour=(0.94, 0.92, 0.86), grain=0.035, mottle=0.04):
    fib = N.spectral((h, w), 1.0, seed, aniso=(1.0, 3.0))
    mot = N.fbm((h, w), seed + 1, 4, base=0.01)
    v = 1 + (fib - 0.5) * grain + (mot - 0.5) * mottle
    return np.clip(np.array(colour, np.float32)[None, None, :] * v[..., None], 0, 1)


def yellow(rgb, seed, amount=0.25, edge=0.35):
    """Uneven yellowing, stronger toward the edges (light/air exposure)."""
    h, w = rgb.shape[:2]
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    dist = np.minimum(np.minimum(xx, w - 1 - xx), np.minimum(yy, h - 1 - yy)) / min(w, h)
    e = np.exp(-dist / 0.08) * edge
    n = N.fbm((h, w), seed, 4, base=0.006)
    t = np.clip(amount * (0.6 + 0.6 * n) + e, 0, 1)[..., None]
    tint = np.array([0.86, 0.74, 0.50], np.float32)
    return rgb * (1 - t) + rgb * tint * t


def fold(rgb, seed, pos, horizontal=True, strength=0.18):
    """A crease: a thin dark line with a lighter ridge beside it and a little grime collected in it."""
    h, w = rgb.shape[:2]
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    wob = (N.fbm((1, w if horizontal else h), seed, 3, base=0.01)[0] - 0.5) * 3
    if horizontal:
        d = yy - (pos * h + wob[None, :])
    else:
        d = xx - (pos * w + wob[:, None])
    shade = -np.exp(-(d / 1.2) ** 2) * strength + np.exp(-((d - 2.5) / 2.0) ** 2) * strength * 0.35
    shade = shade * (0.6 + 0.4 * N.fbm((h, w), seed + 1, 3, base=0.02))
    return np.clip(rgb * (1 + shade[..., None]), 0, 1)


def water_stain(rgb, seed, cx, cy, r, strength=0.22):
    """Dried water mark: brownish interior wash and a darker tide line."""
    h, w = rgb.shape[:2]
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    d = np.sqrt(((xx - cx * w) / (r * w)) ** 2 + ((yy - cy * h) / (r * w * 0.8)) ** 2)
    d = d + (N.fbm((h, w), seed, 4, base=0.012) - 0.5) * 0.6
    inside = N.smoothstep(1.0, 0.85, d) * 0.4
    tide = np.exp(-((d - 0.97) / 0.025) ** 2)
    t = np.clip((inside + tide) * strength, 0, 1)[..., None]
    tint = np.array([0.72, 0.58, 0.38], np.float32)
    return rgb * (1 - t) + rgb * tint * t


def foxing(rgb, seed, count=40, size=3.0, strength=0.25):
    h, w = rgb.shape[:2]
    spots = N.blobs((h, w), seed, count, size * 0.5, size * 1.6, irregular=0.5, wrap=False, rough_base=0.08)
    t = (spots * strength)[..., None]
    return rgb * (1 - t) + rgb * np.array([0.70, 0.52, 0.32], np.float32) * t


def grime(rgb, seed, amount=0.15):
    h, w = rgb.shape[:2]
    n = N.smoothstep(0.45, 0.95, N.warp(N.fbm((h, w), seed, 5, base=0.006), seed + 1, 20, 0.01))
    t = (n * amount)[..., None]
    return rgb * (1 - t) + np.array([0.20, 0.17, 0.13], np.float32) * t


def handling(rgb, seed, amount=0.12):
    """Dirt from hands: darker smudges near the lower corners and the edges."""
    h, w = rgb.shape[:2]
    out = rgb
    for k, (cx, cy) in enumerate(((0.08, 0.92), (0.92, 0.9), (0.5, 0.97))):
        blob = N.blobs((h, w), seed + k, 3, w * 0.03, w * 0.07, irregular=0.8, wrap=False, rough_base=0.02)
        yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
        near = np.exp(-(((xx / w - cx) / 0.15) ** 2 + ((yy / h - cy) / 0.12) ** 2))
        t = (blob * near * amount)[..., None]
        out = out * (1 - t) + np.array([0.25, 0.21, 0.17], np.float32) * t
    return out


def torn_alpha(w, h, seed, inset=8, rough=6.0, torn_sides='tblr', corner_cut=None):
    """Alpha of a sheet whose torn sides wander inward with fractal detail. Returns (alpha, fibre_rim)."""
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    big = (N.fbm((h, w), seed, 4, base=0.01) - 0.5) * rough * 3
    fine = (N.spectral((h, w), 1.2, seed + 1) - 0.5) * rough
    d = np.full((h, w), 1e9, np.float32)
    for side in 'tblr':
        base = {'t': yy, 'b': h - 1 - yy, 'l': xx, 'r': w - 1 - xx}[side] - inset
        if side in torn_sides:
            base = base + big + fine
        else:
            base = base + inset - 1
        d = np.minimum(d, base)
    if corner_cut:
        for (cx, cy, rad) in corner_cut:         # a torn-away corner (fractions)
            dc = np.sqrt((xx - cx * w) ** 2 + (yy - cy * h) ** 2) - rad * w + big + fine
            d = np.minimum(d, dc)
    alpha = N.smoothstep(-0.6, 0.6, d)
    rim = N.smoothstep(-0.6, 0.6, d) * N.smoothstep(3.0, 0.5, d)     # exposed paper fibres along the tear
    return alpha, rim


def tape(rgba, seed, box, angle=0.0, colour=(0.93, 0.86, 0.62), opacity=0.45):
    """Old adhesive tape strip (yellowed, semi-transparent, ragged ends, a little dirt caught in it)."""
    h, w = rgba.shape[:2]
    x0, y0, x1, y1 = box
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    hw, hh = (x1 - x0) / 2, (y1 - y0) / 2
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    u = (xx - cx) * np.cos(angle) + (yy - cy) * np.sin(angle)
    v = -(xx - cx) * np.sin(angle) + (yy - cy) * np.cos(angle)
    jag = (N.spectral((h, w), 1.0, seed) - 0.5) * 5
    m = N.smoothstep(hw + 1, hw - 1, np.abs(u) + jag) * N.smoothstep(hh + 0.8, hh - 0.8, np.abs(v))
    dirt = N.fbm((h, w), seed + 3, 4, base=0.03)
    t = (m * opacity * (0.75 + 0.5 * dirt))[..., None]
    out = rgba.copy()
    out[..., :3] = out[..., :3] * (1 - t) + np.array(colour, np.float32) * out[..., :3].mean(-1, keepdims=True).clip(0.5, 1) * t
    if out.shape[2] == 4:
        out[..., 3] = np.maximum(out[..., 3], m * opacity * 1.6)
    return out


def staple(rgb, x, y, angle=0.0, length=14):
    from PIL import Image as _I, ImageDraw as _D
    h, w = rgb.shape[:2]
    S = 4
    im = _I.new('L', (w * S, h * S), 0)
    d = _D.Draw(im)
    dx, dy = np.cos(angle) * length / 2 * S, np.sin(angle) * length / 2 * S
    d.line([(x * S - dx, y * S - dy), (x * S + dx, y * S + dy)], fill=255, width=2 * S)
    m = np.asarray(im.resize((w, h), _I.LANCZOS), np.float32) / 255
    rust = ndimage.gaussian_filter(m, 2.5) * 0.5
    out = rgb * (1 - rust[..., None]) + np.array([0.45, 0.28, 0.14], np.float32) * rust[..., None]
    out = out * (1 - m[..., None]) + np.array([0.55, 0.55, 0.57], np.float32) * m[..., None]
    return out


def photocopy(gray, seed, contrast=1.7, toner=0.06):
    """Several-generation photocopy look on a [0,1] greyscale photo: crushed blacks, lifted mids, toner speckle and
    a faint drum streak."""
    g = np.clip((gray - 0.5) * contrast + 0.55, 0, 1)
    h, w = g.shape
    speck = N.smoothstep(0.9, 1.0, N.spectral((h, w), 0.4, seed, fmin=0.1)) * toner * 4
    streak = N.spectral((h, w), 2.0, seed + 1, aniso=(40.0, 1.0)) * toner
    g = np.clip(g - speck - (streak - toner / 2), 0, 1)
    g = ndimage.gaussian_filter(g, 0.6)
    return g


def halftone(gray, cell=4.0, angle=0.785):
    """Amplitude-modulated round-dot screen of a [0,1] greyscale image (1 = white). Returns ink coverage [0,1]."""
    h, w = gray.shape
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    u = xx * np.cos(angle) + yy * np.sin(angle)
    v = -xx * np.sin(angle) + yy * np.cos(angle)
    fu = (u / cell) % 1 - 0.5
    fv = (v / cell) % 1 - 0.5
    r = np.sqrt(fu * fu + fv * fv) / 0.7071
    darkness = 1 - gray
    return N.smoothstep(np.sqrt(np.clip(darkness, 0, 1)) + 0.06, np.sqrt(np.clip(darkness, 0, 1)) - 0.06, r)
